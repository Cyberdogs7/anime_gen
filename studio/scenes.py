"""Single owner of scene (location) reference images and their state.

Mirrors :mod:`studio.refs` for locations: ONE place that renders a location ref
image and reads/writes ``scenes/<sid>/refs/refs.json``.
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Callable

from . import prompts
from .config import get_config
from .show import Show


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", (text or "").strip().lower()).strip("-")


def _tokens(text: str) -> set[str]:
    stop = {"the", "a", "an", "of", "in", "at", "to", "and", "on"}
    return {t for t in re.split(r"[^a-z0-9]+", (text or "").lower())
            if t and t not in stop}


def _scene_name(show: Show, sid: str) -> str:
    try:
        import yaml
        y = show.scenes_dir / f"{sid}.yaml"
        if y.exists():
            return str((yaml.safe_load(y.read_text(encoding="utf-8")) or {}).get("name", "") or "")
    except Exception:
        pass
    return ""


# A confident match only: attaching the WRONG location is worse than none.
_MATCH_MIN = 0.5


def resolve_slug(show: Show, text: str) -> str | None:
    """Best registry location slug for a free-text name, or None.

    Exact slug wins. Otherwise the free-text tokens and the registered slug/name
    must be a SUBSET of each other (so "Hangar Pit" -> hangar-pit and
    "pit monitor wall" -> pit-wall), scored by Jaccard. Distinct proper names do
    NOT collapse into each other: "Red's dead cockpit" shares "dead cockpit"
    with "red-s-dead-cockpit" but neither token set contains the other, so it
    resolves to no entry and gets registered as its own place.
    """
    try:
        want = str(text or "").strip()
        if not want:
            return None
        registry = list(show.list_scenes() or [])
        if not registry:
            return None
        slug = slugify(want)
        if slug in registry:
            return slug
        toks = _tokens(want)
        if not toks:
            return None
        best, best_score = None, 0.0
        for sid in registry:
            have = _tokens(sid) | _tokens(_scene_name(show, sid))
            if not have:
                continue
            if not (toks <= have or have <= toks):
                continue
            union = len(toks | have)
            score = len(toks & have) / union if union else 0.0
            if score > best_score:
                best, best_score = sid, score
        return best if (best and best_score >= _MATCH_MIN) else None
    except Exception:
        return None


def location_name(show: Show, sid: str) -> str:
    """The registry display name for a location id ("" when unknown)."""
    return _scene_name(show, sid)


def environment_ref(show: Show, sid: str) -> Path | None:
    """The reference image path for a registry location, if it exists."""
    if not sid:
        return None
    try:
        ref = show.scenes_dir / sid / "refs" / f"{sid}_ref_01.png"
        return ref if ref.exists() else None
    except Exception:
        return None


def registry_block(show: Show) -> list[dict[str, str]]:
    """[{id, name, description}] for the location registry, for prompt injection."""
    out: list[dict[str, str]] = []
    try:
        for sid in show.list_scenes() or []:
            desc = ""
            try:
                import yaml
                y = show.scenes_dir / f"{sid}.yaml"
                if y.exists():
                    d = yaml.safe_load(y.read_text(encoding="utf-8")) or {}
                    desc = str(d.get("description", "") or "")[:200]
            except Exception:
                pass
            out.append({"id": sid, "name": _scene_name(show, sid), "description": desc})
    except Exception:
        pass
    return out


def register_location(show: Show, name: str, description: str = "",
                      setting_prompt: str = "") -> str:
    """Register a location (idempotent) and return its registry slug id.

    Reuses an existing confident match; otherwise writes a new ``scenes/<slug>.yaml``
    so the place becomes canonical and gains a reference image (generated by the
    standard scene-ref pass / :func:`generate_ref`). Never raises.
    """
    name = (name or "").strip()
    try:
        existing = resolve_slug(show, name)
        if existing:
            return existing
    except Exception:
        pass
    sid = slugify(name) or "location"
    try:
        show.scenes_dir.mkdir(parents=True, exist_ok=True)
        base, n = sid, 2
        while (show.scenes_dir / f"{sid}.yaml").exists():
            sid = f"{base}-{n}"
            n += 1
        show.write_scene({
            "id": sid,
            "name": name or sid,
            "description": description or name or sid,
            "setting_prompt": setting_prompt or f"{name}, background only, no people",
        })
    except Exception:
        pass
    return sid


def refs_dir(show: Show, sid: str) -> Path:
    return show.scenes_dir / sid / "refs"


def load_refs(show: Show, sid: str) -> dict[str, Any]:
    p = refs_dir(show, sid) / "refs.json"
    if not p.exists():
        return {}
    try:
        return json.loads(p.read_text(encoding="utf-8")) or {}
    except Exception:
        return {}


def save_refs(show: Show, sid: str, data: dict[str, Any]) -> None:
    rd = refs_dir(show, sid)
    rd.mkdir(parents=True, exist_ok=True)
    (rd / "refs.json").write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")


def generate_ref(show: Show, scene: dict[str, Any], sid: str, cfg=None,
                 report: Callable[[str], None] | None = None,
                 force: bool = False, notes: str = "") -> bool:
    """Render one location ref image (krea2).

    Returns True when an image landed; records a stub (and returns False) when no
    krea2 instance is configured or the render fails, so callers stop retrying.
    """
    cfg = cfg or get_config()
    rd = refs_dir(show, sid)
    rd.mkdir(parents=True, exist_ok=True)
    out = rd / f"{sid}_ref_01.png"
    if out.exists() and not force:
        return True
    if force and out.exists():
        try:
            out.unlink()
        except OSError:
            pass
    krea2 = cfg.get("env", "comfyui", {}).get("krea2", {}) or {}
    if not krea2.get("url"):
        save_refs(show, sid, {"status": "stub",
                              "note": "no krea2 url configured (env.yaml comfyui.krea2.url)"})
        return False
    from .remote import ServiceOps
    name = scene.get("name", "") or sid
    setting = (scene.get("setting_prompt") or scene.get("description") or "").strip()
    if report:
        report(f"Generating scene image: {name} (Krea 2)…")
    style = show.render_style()
    revision = (f" Director's revision: {notes.strip()}"
                if notes.strip() else "")
    prompt = (f"Show location concept art. {setting}".rstrip(" .")
              + revision
              + ". Empty unpopulated establishing shot of the location itself, "
                "cinematic composition. "
              + prompts.ref_style_clause(style, show.ref_medium()))
    out = rd / f"{sid}_ref_01.png"
    anchor = show.dir / "style_anchor.png"
    use_anchor = cfg.get("comfy", "style_anchor", False)
    res = ServiceOps(cfg).generate_image(
        prompt, seed=0, aspect_ratio="16:9", out_path=str(out),
        style_ref=str(anchor) if (use_anchor and anchor.exists()) else "")
    if res.get("ok") and out.exists():
        # Preserve the director's rejected_notes across the render: the next
        # retry's brief rewrite needs them, and nothing else re-records them.
        # Without this a second retry rewrites the brief from empty notes and
        # the same location comes back.
        prev = load_refs(show, sid) or {}
        data: dict[str, Any] = {"status": "real", "refs": [out.name],
                                "seed": res.get("seed", 0)}
        if str(prev.get("rejected_notes") or "").strip():
            data["rejected_notes"] = str(prev["rejected_notes"])
        save_refs(show, sid, data)
        return True
    save_refs(show, sid, {"status": "stub",
                          "note": "krea2 scene ref generation unavailable"})
    return False


# Venue "cores": entries sharing one are the SAME physical place under different
# phrasings ("stadium arena floor", "concrete stadium bowl", "arena floor at the
# north gate"). Cockpits and other proper sets never share a core, so they are
# never merged. The canonical entry is the OLDEST (the series' original place).
_VENUE_CORES = {
    "arena": "arena", "stadium": "arena", "bowl": "arena", "concourse": "arena",
    "bunk": "bunk",
}


def _entry_meta(show: Show, sid: str) -> dict[str, Any]:
    import yaml
    y = show.scenes_dir / f"{sid}.yaml"
    try:
        d = yaml.safe_load(y.read_text(encoding="utf-8")) or {}
    except Exception:
        d = {}
    toks = _tokens(sid) | _tokens(str(d.get("name") or ""))
    core = ""
    if "cockpit" not in toks:
        for k, c in _VENUE_CORES.items():
            if k in toks:
                core = c
                break
    ref = show.scenes_dir / sid / "refs" / f"{sid}_ref_01.png"
    try:
        mtime = y.stat().st_mtime
    except Exception:
        mtime = 0.0
    return {"id": sid, "name": str(d.get("name") or sid), "tokens": toks,
            "core": core, "mtime": mtime, "has_ref": ref.exists()}


def plan_dedupe(show: Show) -> dict[str, str]:
    """Mapping {duplicate_id: canonical_id} for registry entries that are one set."""
    entries = [_entry_meta(show, sid) for sid in (show.list_scenes() or [])]
    groups: dict[str, list[dict[str, Any]]] = {}
    for e in entries:
        if e["core"]:
            groups.setdefault(e["core"], []).append(e)
    mapping: dict[str, str] = {}
    for core, members in groups.items():
        if len(members) < 2:
            continue
        members.sort(key=lambda e: (e["mtime"], 0 if e["has_ref"] else 1, len(e["id"])))
        canonical = members[0]["id"]
        for m in members[1:]:
            mapping[m["id"]] = canonical
    return mapping


def dedupe(show: Show, dry_run: bool = False) -> list[str]:
    """Merge synonym registry entries into one canonical place.

    Deterministic and conservative: only entries sharing a venue core (arena /
    stadium / bowl / concourse, or bunk) merge; distinct cockpits and proper sets
    never do. The oldest entry (the series' original place) wins. Rewrites
    plan/details/script ``location_id`` references, preserves a real reference
    image, and deletes the duplicates. Returns a human-readable log.
    """
    mapping = plan_dedupe(show)
    if not mapping:
        return []
    if dry_run:
        return [f"{d} -> {c}" for d, c in sorted(mapping.items())]
    log: list[str] = []
    import shutil as _shutil

    # 1) Canonical keeps a real ref if it had none but a duplicate did.
    for dup, can in mapping.items():
        cdir = show.scenes_dir / can / "refs"
        cdir.mkdir(parents=True, exist_ok=True)
        cpng = cdir / f"{can}_ref_01.png"
        dpng = show.scenes_dir / dup / "refs" / f"{dup}_ref_01.png"
        if not cpng.exists() and dpng.exists():
            try:
                _shutil.copyfile(dpng, cpng)
                save_refs(show, can, {"status": "real", "refs": [cpng.name], "seed": 0})
                log.append(f"{can}: ref taken from {dup}")
            except Exception:
                pass

    # 2) Rewrite every persisted location_id (plan, details, scripts).
    def _rewrite(obj) -> bool:
        changed = False
        if isinstance(obj, dict):
            lid = obj.get("location_id")
            if isinstance(lid, str) and lid in mapping:
                obj["location_id"] = mapping[lid]
                changed = True
            for v in obj.values():
                changed |= _rewrite(v)
        elif isinstance(obj, list):
            for v in obj:
                changed |= _rewrite(v)
        return changed

    runs = show.dir / "runs"
    if runs.exists():
        for pattern in ("EP*/plan.json", "EP*/scene_details.json", "EP*/script.r*.json"):
            for p in runs.glob(pattern):
                try:
                    d = json.loads(p.read_text(encoding="utf-8"))
                except Exception:
                    continue
                if _rewrite(d):
                    try:
                        p.write_text(json.dumps(d, indent=2, ensure_ascii=False),
                                     encoding="utf-8")
                        log.append(f"rewrote {p.relative_to(show.dir)}")
                    except Exception:
                        pass
        for p in runs.glob("EP*/scenes/*.continuity*.txt"):
            if p.name.split(".")[0] in mapping:
                try:
                    p.unlink()
                except Exception:
                    pass

    # 3) Remove the duplicate entries (yaml + refs dir).
    for dup in sorted(mapping):
        try:
            (show.scenes_dir / f"{dup}.yaml").unlink()
        except Exception:
            pass
        ddir = show.scenes_dir / dup
        if ddir.exists():
            _shutil.rmtree(ddir, ignore_errors=True)
        log.append(f"removed {dup} -> {mapping[dup]}")
    return log


def generate_missing_refs(show: Show, cfg=None, report: Callable[[str], None] | None = None,
                          limit: int = 0) -> int:
    """Render refs for every registry location that still lacks one.

    Called from a GPU phase (never while the local LLM is resident): each
    ``generate_ref`` acquires the GPU manager's COMFYUI lease, which evicts the
    LLM first, so a local model and krea2 never contend for VRAM. Best-effort —
    a failure records a stub so callers stop retrying. Returns how many landed.
    """
    cfg = cfg or get_config()
    did = 0
    try:
        for sid in list(show.list_scenes() or []):
            rd = refs_dir(show, sid)
            if (rd / f"{sid}_ref_01.png").exists():
                continue
            # A stub from an earlier failed attempt is NOT final: retry it once per
            # GPU ref pass (the ref is overwritten on success), so a transient krea2
            # outage can't permanently poison a location.
            try:
                import yaml
                scene = yaml.safe_load((show.scenes_dir / f"{sid}.yaml")
                                       .read_text(encoding="utf-8")) or {}
            except Exception:
                continue
            if generate_ref(show, scene, sid, cfg=cfg, report=report):
                did += 1
            if limit and did >= limit:
                break
    except Exception:
        pass
    return did
